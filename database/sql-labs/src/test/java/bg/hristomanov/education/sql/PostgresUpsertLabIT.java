package bg.hristomanov.education.sql;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.postgresql.ds.PGSimpleDataSource;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;
import org.testcontainers.utility.DockerImageName;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.sql.SQLException;
import java.util.concurrent.CyclicBarrier;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@Testcontainers
class PostgresUpsertLabIT {
    @Container static final PostgreSQLContainer POSTGRES =
            new PostgreSQLContainer(DockerImageName.parse("postgres:17-alpine"));
    private static DataSource datasource;
    private static PostgresUpsertRepository repository;

    @BeforeAll static void schema() throws SQLException {
        var ds = new PGSimpleDataSource();
        ds.setURL(POSTGRES.getJdbcUrl());
        ds.setUser(POSTGRES.getUsername());
        ds.setPassword(POSTGRES.getPassword());
        datasource = ds;
        repository = new PostgresUpsertRepository(datasource);
        try (var c = datasource.getConnection(); var stmt = c.createStatement()) {
            stmt.execute("""
                CREATE TABLE vm24_ledger (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  tenant_id BIGINT NOT NULL,
                  external_ref TEXT NOT NULL,
                  amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
                  CONSTRAINT uq_vm24_ledger_tenant_ref UNIQUE (tenant_id,external_ref)
                )
                """);
        }
    }

    @BeforeEach void empty() throws SQLException {
        try (var c = datasource.getConnection();var stmt = c.createStatement()) {
            stmt.execute("TRUNCATE vm24_ledger RESTART IDENTITY");
        }
    }

    @Test void insertThenUpdatePreservesDomainIdentity() throws SQLException {
        var first = repository.put(10, "ORDER-A", new BigDecimal("20.00"));
        var second = repository.put(10, "ORDER-A", new BigDecimal("25.00"));
        assertThat(second.id()).isEqualTo(first.id());
        assertThat(second.amount()).isEqualByComparingTo("25.00");
        assertThat(count(10, "ORDER-A")).isEqualTo(1);
    }

    @Test void sameReferenceInDifferentTenantsRemainsIndependent() throws SQLException {
        var first = repository.put(10, "ORDER-A", BigDecimal.ONE);
        var second = repository.put(20, "ORDER-A", BigDecimal.TEN);
        assertThat(first.id()).isNotEqualTo(second.id());
        assertThat(count(10, "ORDER-A")).isEqualTo(1);
        assertThat(count(20, "ORDER-A")).isEqualTo(1);
    }

    @Test void concurrentUpsertsSerializeThroughUniqueConstraintWithoutDuplicates() throws Exception {
        var startingGate = new CyclicBarrier(2);
        try (var pool = Executors.newFixedThreadPool(2)) {
            var first = pool.submit(() -> {
                startingGate.await(5, TimeUnit.SECONDS);
                return repository.put(10, "SAME", new BigDecimal("11.00"));
            });
            var second = pool.submit(() -> {
                startingGate.await(5, TimeUnit.SECONDS);
                return repository.put(10, "SAME", new BigDecimal("22.00"));
            });
            var a = first.get(15, TimeUnit.SECONDS);
            var b = second.get(15, TimeUnit.SECONDS);
            assertThat(a.id()).isEqualTo(b.id());
            assertThat(count(10, "SAME")).isEqualTo(1);
            assertThat(storedAmount(10,"SAME")).isIn(new BigDecimal("11.00"), new BigDecimal("22.00"));
        }
    }

    @Test void checkConstraintRejectsNegativeAmountEvenWithOnConflict() throws SQLException {
        repository.put(10, "ORDER-A", BigDecimal.ONE);
        assertThatThrownBy(() -> repository.put(10, "ORDER-A", new BigDecimal("-1.00")))
                .isInstanceOf(SQLException.class)
                .satisfies(e -> assertThat(((SQLException)e).getSQLState()).isEqualTo("23514"));
        assertThat(storedAmount(10, "ORDER-A")).isEqualByComparingTo("1.00");
    }

    private static int count(long tenantId, String ref) throws SQLException {
        try (var c = datasource.getConnection();
             var stmt = c.prepareStatement("""
                 SELECT COUNT(*) FROM vm24_ledger WHERE tenant_id = ? AND external_ref = ?
                 """)) {
            stmt.setLong(1, tenantId);
            stmt.setString(2, ref);
            try (var rs = stmt.executeQuery()) { rs.next(); return rs.getInt(1); }
        }
    }

    private static BigDecimal storedAmount(long tenantId, String ref) throws SQLException {
        try (var c = datasource.getConnection();
             var stmt = c.prepareStatement("""
                 SELECT amount FROM vm24_ledger WHERE tenant_id = ? AND external_ref = ?
                 """)) {
            stmt.setLong(1, tenantId);
            stmt.setString(2, ref);
            try (var rs = stmt.executeQuery()) { rs.next(); return rs.getBigDecimal(1); }
        }
    }
}
