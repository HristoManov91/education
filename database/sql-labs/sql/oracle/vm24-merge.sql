-- Use a dedicated schema. Database uniqueness and concurrency need real Oracle validation.
CREATE TABLE vm24_ledger (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id NUMBER(19) NOT NULL,
    external_ref VARCHAR2(80 CHAR) NOT NULL,
    amount NUMBER(12,2) NOT NULL CHECK (amount >= 0),
    CONSTRAINT uq_vm24_ledger_tenant_ref UNIQUE (tenant_id, external_ref)
);

MERGE INTO vm24_ledger target
USING (SELECT 10 AS tenant_id, 'ORDER-1' AS external_ref, 42 AS amount FROM dual) source
   ON (target.tenant_id = source.tenant_id AND target.external_ref = source.external_ref)
WHEN MATCHED THEN UPDATE SET target.amount = source.amount
WHEN NOT MATCHED THEN
  INSERT (tenant_id, external_ref, amount)
  VALUES (source.tenant_id, source.external_ref, source.amount);

COMMIT;
